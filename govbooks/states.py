STATE_ABBR: dict[str, str] = {name: abbr for abbr, name in US_STATES.items()}


def resolve_state(value: str) -> str:
    """Return the full state name for an abbreviation or name, case-insensitively."""
    value = value.strip()
    if value.upper() in US_STATES:
        return US_STATES[value.upper()]
    for name in US_STATES.values():
        if name.lower() == value.lower():
            return name
    raise ValueError(f"Unknown US state: {value!r}")
